#[path = "../../src/proto.rs"]
pub mod proto;

/// Cross tests with the Python agent library (agent/). Python builds codes, Rust checks them
/// (fixtures/py_to_rust.json); Rust signs replies, Python checks them (fixtures/rust_to_py.json).
/// Regenerate the Rust side with `PA_WRITE_FIXTURES=1 cargo test`.
#[cfg(test)]
mod interop {
    use crate::proto::*;
    use ed25519_dalek::{SigningKey, VerifyingKey};
    use sha2::{Digest, Sha256};

    fn fixture(name: &str) -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures").join(name)
    }
    fn py() -> serde_json::Value {
        serde_json::from_str(&std::fs::read_to_string(fixture("py_to_rust.json")).expect("fixture")).unwrap()
    }
    fn s<'a>(v: &'a serde_json::Value, k: &str) -> &'a str { v[k].as_str().unwrap() }
    fn agent_pk(v: &serde_json::Value) -> VerifyingKey {
        VerifyingKey::from_bytes(&hex::decode(s(v, "agent_pk")).unwrap().try_into().unwrap()).unwrap()
    }
    /// The Rust tests' public TEST app key, same as in proto.rs.
    fn app() -> SigningKey { SigningKey::from_bytes(&[7u8; 32]) }
    const AT: u64 = 1_800_000_000;

    #[test]
    fn python_request_is_accepted() {
        let v = py();
        let agents = [Agent::new("pa test agent", agent_pk(&v))];
        let now = v["now"].as_u64().unwrap();
        let (req, view, ag) = decode_request(s(&v, "request"), &agents).expect("Python request verifies and parses");
        assert_eq!(ag.kid, kid(&agent_pk(&v)));
        check_time(&req, now).expect("expiry within 10 minutes");
        assert_eq!(req.id, s(&v, "request_id"));
        assert_eq!(req.action, s(&v, "action"), "the exact action bytes travel in the request");
        assert_eq!(req.hash(), hex::encode(Sha256::digest(s(&v, "action").as_bytes())), "same action hashing");
        assert_eq!(req.hash(), s(&v, "request_hash"));
        assert_eq!(action_code(&req.hash()), "F961 B2D1");
        assert_eq!(summary_line(&view).as_deref(), Some(s(&v, "request_summary")));
        assert_eq!(summary_line(&view).as_deref(), Some("Merge PR #2 into main → tnvolman/typewright-website-audit"));
        assert!(is_elevated(&view));
        // Python's compact JSON is byte-identical to what serde_json writes for the same request.
        let body = s(&v, "request").strip_prefix(REQ_PREFIX).unwrap().split_once('.').unwrap().0.to_string();
        use base64::{engine::general_purpose::URL_SAFE_NO_PAD as B64, Engine};
        assert_eq!(B64.decode(body).unwrap(), serde_json::to_vec(&req).unwrap());

        // A lying title from Python: the Prime still shows the parsed action.
        let (_, lying, _) = decode_request(s(&v, "lying_request"), &agents).expect("lying request");
        assert_eq!(summary_line(&lying).as_deref(), Some(s(&v, "lying_summary")));
        // Unknown tool from Python: raw view, high impact.
        let (raw, unknown, _) = decode_request(s(&v, "unknown_request"), &agents).expect("unknown request");
        assert!(matches!(unknown, ActionView::Unknown { .. }) && is_elevated(&unknown));
        assert_eq!(raw.hash(), s(&v, "unknown_hash"));
        // Signed by an unpaired key: refused.
        let other = [Agent::new("x", SigningKey::from_bytes(&[2u8; 32]).verifying_key())];
        assert!(matches!(decode_request(s(&v, "request"), &other), Err(Reject::BadSignature)));
    }

    #[test]
    fn python_pair_offer_is_accepted() {
        let v = py();
        let pk = decode_pair_offer(s(&v, "pair_offer"), Some(v["now"].as_u64().unwrap())).expect("offer");
        assert_eq!(pk, agent_pk(&v));
    }

    /// Rust-signed answers to the Python fixtures, for agent/tests/test_interop.py.
    #[test]
    fn rust_replies_for_python() {
        let v = py();
        let agents = [Agent::new("pa test agent", agent_pk(&v))];
        let (req, _, _) = decode_request(s(&v, "request"), &agents).unwrap();
        let app = app();
        let out = serde_json::json!({
            "note": "Generated by host-tests (PA_WRITE_FIXTURES=1 cargo test). Test keys only.",
            "app_pk": hex::encode(app.verifying_key().as_bytes()),
            "reply_approve": encode_reply(&req, true, None, &app, AT),
            "reply_deny_wrong_action": encode_reply(&req, false, Some("wrong_action"), &app, AT),
            "reply_deny": encode_reply(&req, false, None, &app, AT),
            "paired_reply": encode_paired_reply(&agent_pk(&v), &app),
            "pairing_code": pairing_code(&agent_pk(&v), &app.verifying_key()),
            "pairing_code_1_7": pairing_code(&SigningKey::from_bytes(&[1u8; 32]).verifying_key(), &app.verifying_key()),
        });
        let text = serde_json::to_string_pretty(&out).unwrap() + "\n";
        let path = fixture("rust_to_py.json");
        if std::env::var("PA_WRITE_FIXTURES").is_ok() {
            std::fs::write(&path, &text).unwrap();
        }
        assert_eq!(std::fs::read_to_string(&path).expect("run with PA_WRITE_FIXTURES=1 once"), text, "Rust output drifted from the fixture");
        assert!(verify_reply(out["reply_approve"].as_str().unwrap(), &app.verifying_key(), &req.id, &req.kid, &req.hash()));
    }
}

/// Shared action-parsing cases (fixtures/actions.json); agent/tests/test_actions.py runs the same file.
#[cfg(test)]
mod actions {
    use crate::proto::*;

    #[test]
    fn shared_action_cases() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("fixtures/actions.json");
        let v: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        for c in v["cases"].as_array().unwrap() {
            let a = c["action"].as_str().unwrap();
            let got = action_view(a);
            match c["expect"].as_str().unwrap() {
                "reject" => assert!(got.is_err(), "{a:?} should be rejected, got {got:?}"),
                "unknown" => assert!(matches!(got, Ok(ActionView::Unknown { .. })), "{a:?}: {got:?}"),
                line => {
                    let view = got.unwrap_or_else(|e| panic!("{a:?}: {e}"));
                    assert_eq!(summary_line(&view).as_deref(), Some(line));
                    let ActionView::Known { detail, .. } = &view else { unreachable!() };
                    assert_eq!(Some(detail.as_str()), c["detail"].as_str());
                }
            }
        }
    }
}
