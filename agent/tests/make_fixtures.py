"""Writes host-tests/fixtures/py_to_rust.json: codes built by the Python library, checked by Rust.

Deterministic (Ed25519 signatures are), so test_interop.py regenerates it and requires an exact match.
The agent key is a public TEST key (seed = 32 bytes of 0x01), never for real use.
Run: python agent/tests/make_fixtures.py
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from primeapprove.protocol import build_request, encode_pair_offer, public_bytes, signing_key, summary_line  # noqa: E402

FIXTURES = Path(__file__).resolve().parents[2] / "host-tests" / "fixtures"
TEST_AGENT_SEED = bytes([1]) * 32
NOW = 1_800_000_000
ACTION = b'{"tool":"github.merge_pull_request","repo":"tnvolman/typewright-website-audit","pr":2,"base":"main","method":"squash","head":"33393c61b3e595bfb83bb9b909e280b2f40f0976"}'


LYING_ACTION = b'{"tool":"github.merge_pull_request","repo":"evil/other-repo","pr":9,"base":"release","method":"merge","head":"0000000000000000000000000000000000000001"}'
UNKNOWN_ACTION = b'{"tool":"github.delete_repo","repo":"tnvolman/typewright-website-audit"}'


def py_to_rust() -> dict:
    sk = signing_key(TEST_AGENT_SEED)
    r = build_request(sk, ACTION, "Merge PR #2 into main", "Squash merge at 33393c6.\n10 files changed.",
                      agent="pa test agent", ttl=600, now=NOW, req_id=bytes(range(16)))
    lying = build_request(sk, LYING_ACTION, "Merge PR #2 into main", "Merge -> PR #2 -> tnvolman/typewright-website-audit",
                          agent="pa test agent", ttl=300, now=NOW, req_id=bytes(range(16, 32)))
    unknown = build_request(sk, UNKNOWN_ACTION, "Run the unit tests", agent="pa test agent", ttl=300, now=NOW,
                            req_id=bytes(range(32, 48)))
    return {
        "note": "Generated by agent/tests/make_fixtures.py. Test agent key only.",
        "agent_pk": public_bytes(sk).hex(),
        "now": NOW,
        "action": ACTION.decode(),
        "request": r.qr, "request_id": r.id, "request_hash": r.hash, "request_exp": r.exp,
        "request_summary": summary_line(r.view),
        "lying_request": lying.qr, "lying_summary": summary_line(lying.view),
        "unknown_request": unknown.qr, "unknown_hash": unknown.hash,
        "pair_offer": encode_pair_offer(sk, NOW + 600),
    }


if __name__ == "__main__":
    FIXTURES.mkdir(exist_ok=True)
    (FIXTURES / "py_to_rust.json").write_text(json.dumps(py_to_rust(), indent=1) + "\n")
    print("wrote", FIXTURES / "py_to_rust.json")
